// normalizeCityCode 将定位得到的区县级 adcode 归一化为地级市 adcode。
// 例如宿豫区 321311 会统一为宿迁市 321300，避免高德城市限制搜索使用错误层级编码。
export function normalizeCityCode(adcode) {
  const code = String(adcode || '').trim()
  if (!/^\d{6}$/.test(code)) return code

  const prefectureCode = `${code.slice(0, 4)}00`
  if (cities.some(city => city.adcode === prefectureCode)) return prefectureCode

  // 直辖市没有 110100 这类地级市编码，需要回退到 110000 等省级直辖市编码。
  const municipality = cities.find(city => city.adcode.endsWith('0000') && city.adcode.slice(0, 2) === code.slice(0, 2))
  return municipality?.adcode || code
}
// readSelectedCity 读取用户明确手动选择的工作城市。
export function readSelectedCity() {
  try { return JSON.parse(localStorage.getItem(CITY_STORAGE_KEY) || 'null') } catch { return null }
}

// saveSelectedCity 保存用户手动选择的城市，首页会据此限制地点搜索范围。
export function saveSelectedCity(city) {
  localStorage.setItem(CITY_STORAGE_KEY, JSON.stringify(city))
}

// readCurrentCity 读取最近一次自动定位城市；数据异常时返回空值，避免阻塞页面渲染。
export function readCurrentCity() {
  try {
    const city = JSON.parse(localStorage.getItem(CURRENT_CITY_STORAGE_KEY) || 'null')
    if (!city?.adcode) return city
    return { ...city, adcode: normalizeCityCode(city.adcode) }
  } catch { return null }
}

// saveCurrentCity 保存定位得到的城市名称和行政区编码，并通知当前打开的页面立即刷新。
export function saveCurrentCity(city) {
  if (!city?.name || !city?.adcode) return
  const normalizedCity = { name: city.name, adcode: normalizeCityCode(city.adcode) }
  localStorage.setItem(CURRENT_CITY_STORAGE_KEY, JSON.stringify(normalizedCity))
  window.dispatchEvent(new CustomEvent(CURRENT_CITY_CHANGED_EVENT, { detail: normalizedCity }))
}